// Helper functions for easy querying
export function getReferenceById(id: string): ReferenceSource | undefined {
  return REAL_REFERENCES.find(r => r.id === id);
}

export function getReferencesByIds(ids: string[]): ReferenceSource[] {
  return REAL_REFERENCES.filter(r => ids.includes(r.id));
}

export function getReferencesByCraft(craftId: string): ReferenceSource[] {
  return REAL_REFERENCES.filter(r => r.relatedCraftId === craftId);
}
